#!/usr/bin/env bash
# Writes thorvg-src/ next to CMakeLists.txt: the ThorVG submodule with patches/ applied, only
# what the runtime compiles (CPU engine, Lottie and raw loaders, rapidjson; no JerryScript, no
# GPU engines, no tests). The npm package ships it, so builds need neither git nor the patches.
# Usage: scripts/vendor-thorvg.sh   (also run by scripts/prepack.sh, on `npm pack` and `npm publish`)
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/thorvg-src"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

"$root/scripts/prepare-thorvg.sh" "$tmp/thorvg" >/dev/null
rm -rf "$out"
mkdir -p "$out"
cd "$tmp/thorvg"
# Directories copied whole, and directories whose files (not subdirectories) are copied.
whole=(inc src/loaders/lottie/rapidjson)
flat=(src/common src/renderer src/renderer/cpu_engine src/loaders/lottie src/loaders/raw)
# Plain cp (no GNU --parents): the script runs on macOS too, for the iOS build.
for dir in "${whole[@]}"; do
    mkdir -p "$out/$(dirname "$dir")"
    cp -R "$dir" "$out/$dir"
done
cp LICENSE "$out"
for dir in "${flat[@]}"; do
    mkdir -p "$out/$dir"
    find "$dir" -maxdepth 1 -type f \( -name '*.cpp' -o -name '*.h' \) -exec cp {} "$out/$dir" \;
done

base=$(git -C "$root/thorvg" rev-parse HEAD)
{
    echo "# ThorVG, patched"
    echo
    echo "Generated by \`scripts/vendor-thorvg.sh\` of @lordicon/runtime: [ThorVG](https://github.com/thorvg/thorvg)"
    echo "at commit \`$base\` with these patches applied, in order (see \`../patches\` and"
    echo "\`../THIRD_PARTY.md\`):"
    echo
    for p in "$root"/patches/*.patch; do echo "- \`$(basename "$p")\`"; done
    echo
    echo "Only what the runtime compiles is here. MIT License: \`LICENSE\`."
} > "$out/README.md"
echo "ThorVG ${base:0:8} + $(ls "$root"/patches/*.patch | wc -l) patches -> thorvg-src ($(du -sh "$out" | cut -f1))"
